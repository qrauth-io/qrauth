import { describe, it, expect, vi } from 'vitest';
import Fastify from 'fastify';
import { generateKeyPairSync } from 'node:crypto';
import { slh_dsa_sha2_128s } from '@noble/post-quantum/slh-dsa.js';
import {
  benchmarkSignatures,
  isNativeSlhDsaAvailable,
  nativeImplementation,
  nativePrivateKey,
  nativePublicKey,
  nobleImplementation,
  runSelfTest,
  selectSlhDsaImplementation,
  SIGNATURE_BYTES,
  type SlhDsaImplementation,
} from '../slh-dsa.js';
import {
  SELF_TEST_MESSAGE,
  SELF_TEST_NOBLE_SIGNATURE,
  SELF_TEST_PUBLIC_KEY,
  SELF_TEST_SECRET_KEY,
} from '../slh-dsa-self-test-vector.js';
import { BENCH_SIGNATURES, registerSlhDsaBenchRoute } from '../slh-dsa-bench.js';

const NATIVE = isNativeSlhDsaAvailable();
// The Node 24 CI step sets this so the cross-verification suite can never
// pass by skipping.
const REQUIRE_NATIVE = process.env.REQUIRE_NATIVE_SLH_DSA === '1';
const SLOW = 60_000; // one pure-JS signature takes seconds on CI runners

// Fast fakes for the selection logic. `goodNoble` returns a real, valid
// reference signature, so the real verifier accepts it without a slow sign.
const goodNoble: SlhDsaImplementation = {
  name: 'noble',
  sign: () => new Uint8Array(SELF_TEST_NOBLE_SIGNATURE),
  verify: nobleImplementation.verify,
};
const brokenNoble: SlhDsaImplementation = {
  name: 'noble',
  sign: () => {
    throw new Error('noble sign exploded');
  },
  verify: () => false,
};
const goodNative: SlhDsaImplementation = { ...goodNoble, name: 'native' };
const wrongSignatureNative: SlhDsaImplementation = {
  name: 'native',
  sign: () => new Uint8Array(SIGNATURE_BYTES),
  verify: () => true,
};

function fakeLogger() {
  return { info: vi.fn(), error: vi.fn() };
}

describe('self-test vector', () => {
  it('is internally consistent (pure-JS verifier)', () => {
    expect(SELF_TEST_SECRET_KEY.subarray(32).equals(SELF_TEST_PUBLIC_KEY)).toBe(true);
    expect(SELF_TEST_NOBLE_SIGNATURE.length).toBe(SIGNATURE_BYTES);
    expect(
      slh_dsa_sha2_128s.verify(SELF_TEST_NOBLE_SIGNATURE, SELF_TEST_MESSAGE, SELF_TEST_PUBLIC_KEY),
    ).toBe(true);
  });
});

describe('built-in availability', () => {
  it('is present when the Node 24 CI step requires it', () => {
    if (REQUIRE_NATIVE) expect(NATIVE).toBe(true);
    expect(typeof NATIVE).toBe('boolean');
  });
});

describe.skipIf(!NATIVE)('cross-verification: built-in <-> pure-JS', () => {
  it('imports the stored raw 64-byte key format without conversion on disk', () => {
    const key = nativePrivateKey(SELF_TEST_SECRET_KEY);
    expect(key.asymmetricKeyType).toBe('slh-dsa-sha2-128s');
    // The public half of the raw secret key is the raw public key.
    const spki = nativePublicKey(SELF_TEST_PUBLIC_KEY).export({ format: 'der', type: 'spki' });
    expect(spki.subarray(spki.length - 32).equals(SELF_TEST_PUBLIC_KEY)).toBe(true);
  });

  it('built-in signature verifies with the pure-JS verifier', () => {
    const message = Buffer.from('merkle-root-under-test');
    const signature = nativeImplementation.sign(message, SELF_TEST_SECRET_KEY);

    expect(signature.length).toBe(SIGNATURE_BYTES);
    expect(slh_dsa_sha2_128s.verify(signature, message, SELF_TEST_PUBLIC_KEY)).toBe(true);
    expect(slh_dsa_sha2_128s.verify(signature, Buffer.from('other'), SELF_TEST_PUBLIC_KEY)).toBe(false);
  });

  it('pure-JS signature verifies with the built-in verifier', () => {
    expect(
      nativeImplementation.verify(SELF_TEST_NOBLE_SIGNATURE, SELF_TEST_MESSAGE, SELF_TEST_PUBLIC_KEY),
    ).toBe(true);
    expect(
      nativeImplementation.verify(SELF_TEST_NOBLE_SIGNATURE, Buffer.from('other'), SELF_TEST_PUBLIC_KEY),
    ).toBe(false);
  });

  // Pure-JS signatures are slow (seconds), so the pure-JS -> built-in
  // direction uses the fixed reference signature above; these tests sign
  // natively and verify with the pure-JS library.
  it('a key generated by the pure-JS library (the stored format) signs natively', { timeout: SLOW }, () => {
    const { secretKey, publicKey } = slh_dsa_sha2_128s.keygen(new Uint8Array(48).fill(7));
    const message = Buffer.from('fresh pure-JS key');

    const nativeSig = nativeImplementation.sign(message, secretKey);
    expect(slh_dsa_sha2_128s.verify(nativeSig, message, publicKey)).toBe(true);
    expect(nativeImplementation.verify(nativeSig, message, publicKey)).toBe(true);
  });

  it('a key generated by Node has the same raw layout the pure-JS library uses', () => {
    const { privateKey, publicKey } = generateKeyPairSync('slh-dsa-sha2-128s' as never);
    const der = privateKey.export({ format: 'der', type: 'pkcs8' });
    const raw = der.subarray(der.length - 64);
    const spki = publicKey.export({ format: 'der', type: 'spki' });
    expect(raw.subarray(32).equals(spki.subarray(spki.length - 32))).toBe(true);

    const message = Buffer.from('fresh built-in key');
    const nativeSig = nativeImplementation.sign(message, raw);
    expect(slh_dsa_sha2_128s.verify(nativeSig, message, raw.subarray(32))).toBe(true);
  });

  it('the real built-in implementation passes the startup self-test', () => {
    expect(runSelfTest(nativeImplementation)).toEqual({ ok: true });
  });

  it('auto mode selects the built-in implementation', () => {
    const logger = fakeLogger();
    const selection = selectSlhDsaImplementation({ logger });

    expect(selection.implementation.name).toBe('native');
    expect(logger.info).toHaveBeenCalledWith(
      expect.objectContaining({ implementation: 'native', node: process.versions.node }),
      'slh-dsa implementation selected',
    );
    expect(logger.error).not.toHaveBeenCalled();
  });
});

describe('nativePrivateKey / nativePublicKey input checks', () => {
  it('reject keys of the wrong length before calling node:crypto', () => {
    expect(() => nativePrivateKey(new Uint8Array(63))).toThrow(/64 bytes/);
    expect(() => nativePublicKey(new Uint8Array(33))).toThrow(/32 bytes/);
  });
});

describe('runSelfTest', () => {
  it('passes for an implementation whose signatures the reference accepts', () => {
    expect(runSelfTest(goodNative)).toEqual({ ok: true });
  });

  it('fails when the reference verifier rejects the signature', () => {
    const result = runSelfTest(wrongSignatureNative);
    expect(result.ok).toBe(false);
    expect(result.error).toMatch(/noble verifier rejected the native signature/);
  });

  it('fails when the implementation rejects the reference signature', () => {
    const rejecting: SlhDsaImplementation = { ...goodNative, verify: () => false };
    expect(runSelfTest(rejecting).error).toMatch(/native verifier rejected the reference signature/);
  });

  it('fails on a wrong-length signature and on exceptions', () => {
    const short: SlhDsaImplementation = { ...goodNative, sign: () => new Uint8Array(10) };
    expect(runSelfTest(short).error).toMatch(/10 bytes/);
    expect(runSelfTest(brokenNoble).error).toBe('noble sign exploded');
  });

  it('the reference signature passes the real pure-JS verifier (fallback self-test, verify half)', () => {
    expect(runSelfTest(goodNoble, nobleImplementation)).toEqual({ ok: true });
  });
});

describe('selectSlhDsaImplementation', () => {
  it('selects the built-in implementation when its self-test passes', () => {
    const logger = fakeLogger();
    const selection = selectSlhDsaImplementation({ logger, native: goodNative, noble: goodNoble });

    expect(selection).toEqual({ implementation: goodNative, nativeAvailable: true });
    expect(logger.info).toHaveBeenCalledTimes(1);
  });

  it('falls back to pure-JS when the built-in is unavailable (Node 22)', () => {
    const logger = fakeLogger();
    const selection = selectSlhDsaImplementation({ logger, native: null, noble: goodNoble });

    expect(selection.implementation).toBe(goodNoble);
    expect(selection.nativeAvailable).toBe(false);
    expect(selection.fallbackReason).toBeUndefined();
    expect(logger.info).toHaveBeenCalledWith(
      expect.objectContaining({ implementation: 'noble', nativeAvailable: false }),
      'slh-dsa implementation selected',
    );
    expect(logger.error).not.toHaveBeenCalled();
  });

  it('falls back to pure-JS and logs an error when the built-in self-test fails', () => {
    const logger = fakeLogger();
    const selection = selectSlhDsaImplementation({ logger, native: wrongSignatureNative, noble: goodNoble });

    expect(selection.implementation).toBe(goodNoble);
    expect(selection.nativeAvailable).toBe(true);
    expect(selection.fallbackReason).toMatch(/^self-test failed:/);
    expect(logger.error).toHaveBeenCalledWith(
      expect.objectContaining({ implementation: 'native' }),
      'slh-dsa built-in self-test failed; falling back to pure-JS',
    );
  });

  it('uses pure-JS when forced with SIGNER_SLH_DSA_IMPL=noble', () => {
    const logger = fakeLogger();
    const selection = selectSlhDsaImplementation({ logger, mode: 'noble', native: goodNative, noble: goodNoble });

    expect(selection.implementation).toBe(goodNoble);
    expect(selection.fallbackReason).toBe('disabled by SIGNER_SLH_DSA_IMPL=noble');
  });

  it('throws (refuse to start) only when both implementations fail', () => {
    const logger = fakeLogger();

    expect(() =>
      selectSlhDsaImplementation({ logger, native: wrongSignatureNative, noble: brokenNoble }),
    ).toThrow(/No working SLH-DSA implementation/);
    expect(logger.error).toHaveBeenCalledTimes(2);

    expect(() => selectSlhDsaImplementation({ logger, native: null, noble: brokenNoble })).toThrow();
  });
});

describe('POST /internal/slh-dsa-bench', () => {
  it('times a fixed number of test-key signatures with the active implementation', async () => {
    const sign = vi.fn(goodNative.sign);
    const impl: SlhDsaImplementation = { ...goodNative, sign };
    const app = Fastify({ logger: false });
    registerSlhDsaBenchRoute(app, () => ({ implementation: impl, nativeAvailable: true }));

    const res = await app.inject({ method: 'POST', url: '/internal/slh-dsa-bench' });
    const body = res.json();

    expect(res.statusCode).toBe(200);
    expect(body.implementation).toBe('native');
    expect(body.node).toBe(process.versions.node);
    expect(body.timingsMs).toHaveLength(BENCH_SIGNATURES);
    expect(typeof body.medianMs).toBe('number');
    expect(sign).toHaveBeenCalledTimes(BENCH_SIGNATURES);
    for (const call of sign.mock.calls) expect(Buffer.from(call[1]).equals(SELF_TEST_SECRET_KEY)).toBe(true);
    await app.close();
  });

  it('benchmarkSignatures returns one rounded timing per signature', () => {
    const timings = benchmarkSignatures(goodNative, 3);
    expect(timings).toHaveLength(3);
    for (const t of timings) expect(t).toBeGreaterThanOrEqual(0);
  });
});
